function julia(
  id: string,
  label: string,
  detail: string,
  preset: string,
  center: [number, number],
  zoomSize: number,
  iterations: number,
  group: string,
): EscapeTimePlace {
  return {
    id,
    label,
    detail,
    center,
    zoomSize,
    iterations,
    group,
    parameters: { preset, ...JULIA_PRESETS[preset] },
    preview: `/assets/place-previews/julia-${id}.webp`,
  };
}

